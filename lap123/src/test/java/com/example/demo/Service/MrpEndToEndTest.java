        jdbc.update("INSERT INTO taikhoan VALUES ('manager@test.local', 1), ('employee@test.local', 2), ('other@test.local', 3)");
        jdbc.update("INSERT INTO sanpham VALUES (1, 'Laptop A', 0)");
        jdbc.update("INSERT INTO nguyenvatlieu VALUES (1, 'RAM', 'RAM 16GB', 'Cái', 100, 0, 2, 1)");
